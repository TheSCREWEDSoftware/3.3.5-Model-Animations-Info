#!/usr/bin/env python3
"""Step 2. Turns data/model_anims.json into the compact data the page embeds (data/payload.json)
and into the Lua table for server scripts.

    python3 build_payload.py <model_anims.json> <payload.json> [<ModelAnimData.lua>]
"""
import json, os, sys

SRC, OUT = sys.argv[1:3]
LUA = sys.argv[3] if len(sys.argv) > 3 else None
d = json.load(open(SRC))

ANIMS = {int(k): v for k, v in d["anims"].items()}
MODEL_PATH = {int(k): v for k, v in d["modeldata"].items()}        # model id -> path as written in the DBC
DISPLAYS = {int(k): v for k, v in d["displays"].items()}
PLAYABLE_RACES = {1, 2, 3, 4, 5, 6, 7, 8, 10, 11}


def key(path):
    return os.path.splitext(path)[0].lower() + ".m2"


models = {k: sorted(v["anims"]) for k, v in d["models"].items() if "anims" in v}
order = sorted(models)
index = {k: i for i, k in enumerate(order)}


def model_of(display):
    """index of the model a display ID uses, or None when the model file is missing"""
    return index.get(key(MODEL_PATH.get(DISPLAYS[display]["model"], "")))


forms = {}
for f in d["forms"].values():
    for display in f["displays"]:
        forms.setdefault(display, []).append(f["name"])

# animations that every playable race and gender has: the yardstick for "what a normal player has"
common = None
for race_id, race in d["races"].items():
    if int(race_id) in PLAYABLE_RACES:
        for gender in ("male", "female"):
            anims = set(models[order[model_of(race[gender])]])
            common = anims if common is None else common & anims

payload = {
    "anims": {i: [a["name"], a["fallback"]] for i, a in ANIMS.items()},
    "models": [[k, models[k], d["models"][k]["src"]] for k in order],
    "displays": {i: model_of(i) for i in DISPLAYS if model_of(i) is not None},
    "broken": {i: MODEL_PATH.get(v["model"]) or "model id %d, which does not exist" % v["model"] for i, v in DISPLAYS.items() if model_of(i) is None},
    "forms": forms,
    "common": sorted(common),
}
json.dump(payload, open(OUT, "w"), separators=(",", ":"))
print("wrote", OUT, "-", len(order), "models,", len(payload["displays"]), "display IDs,", len(common), "animations shared by all players")

if LUA:
    def plays(anims, i):
        """animation the client falls back to (AnimationData.dbc), or None"""
        seen = set()
        while i not in anims:
            if i in seen or i not in ANIMS:
                return None
            seen.add(i)
            i = ANIMS[i]["fallback"]
        return i

    # name, bit, test
    CAPS = [("WALK_RUN", 1, lambda a: 4 in a or 5 in a), ("JUMP", 2, lambda a: {37, 38, 39} <= a), ("FALL", 4, lambda a: 40 in a),
            ("SWIM", 8, lambda a: {41, 42} <= a), ("STRAFE", 16, lambda a: {11, 12} <= a), ("ATTACK", 32, lambda a: bool(plays(a, 16))),
            ("CAST", 64, lambda a: bool(plays(a, 53))), ("DEATH", 128, lambda a: 1 in a), ("SIT", 256, lambda a: 97 in a), ("MOUNTED", 512, lambda a: 91 in a)]
    with open(LUA, "w") as f:
        f.write("-- Generated by tools/build_payload.py from the 3.3.5a client files.\n")
        f.write("-- Which animations each creature display ID really has.\n")
        f.write("--   local MA = require('ModelAnimData')\n")
        f.write("--   MA.Has(displayId, MA.JUMP)      -- true when that model has a complete jump\n")
        f.write("--   MA.Works(displayId)             -- true when nothing a player needs is missing\n")
        f.write("local MA = {}\n")
        for name, bit, _ in CAPS:
            f.write("MA.%s = %d\n" % (name, bit))
        f.write("MA.ALL = %d\n" % sum(bit for _, bit, _ in CAPS))
        f.write("-- model index -> capability bits\nMA.models = {\n")
        for i, k in enumerate(order):
            anims = set(models[k])
            f.write("  %d, -- %d %s\n" % (sum(bit for _, bit, test in CAPS if test(anims)), i + 1, k))
        f.write("}\n-- display ID -> model index\nMA.displays = {\n")
        pairs = ["[%d]=%d" % (i, m + 1) for i, m in sorted(payload["displays"].items())]
        for i in range(0, len(pairs), 12):
            f.write("  " + ",".join(pairs[i:i + 12]) + ",\n")
        f.write("}\n")
        f.write("local band = bit and bit.band or bit32 and bit32.band or function(a, b)\n"
                "  local r, p = 0, 1\n"
                "  while a > 0 and b > 0 do\n"
                "    if a % 2 == 1 and b % 2 == 1 then r = r + p end\n"
                "    a, b, p = math.floor(a / 2), math.floor(b / 2), p * 2\n"
                "  end\n"
                "  return r\n"
                "end\n")
        f.write("function MA.Caps(displayId) local m = MA.displays[displayId] return m and MA.models[m] or nil end\n")
        f.write("function MA.Has(displayId, cap) local c = MA.Caps(displayId) return c ~= nil and band(c, cap) == cap end\n")
        f.write("function MA.Works(displayId) return MA.Has(displayId, MA.ALL) end\n")
        f.write("return MA\n")
    print("wrote", LUA)
